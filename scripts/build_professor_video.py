"""Prepares the video avatar: web clips, poster, and per-frame mouth tracking.

The clips (Kling, all starting and ending on the same hero frame, lips closed) carry the body motion. While he
speaks, src/lib/mouthWarp.ts animates his own mouth in the frame; it needs to know where the mouth is in every
frame (the head nods a little), which this script measures.

Needs numpy + opencv (run with the voice-lab venv):
  ~/bclt-voice-lab/.venv/bin/python -I scripts/build_professor_video.py WEB_CLIPS_DIR
Writes src/assets/professor-video/: <clip>.mp4, poster.jpg and track.ts.
"""
import json
import shutil
import sys
from pathlib import Path

import cv2
import numpy as np

OUT = Path(__file__).resolve().parent.parent / 'src' / 'assets' / 'professor-video'


def frames_of(path):
    video = cv2.VideoCapture(str(path))
    fps = video.get(cv2.CAP_PROP_FPS)
    frames = []
    while True:
        ok, frame = video.read()
        if not ok:
            return frames, fps
        frames.append(frame)


def gray(image):
    return cv2.cvtColor(image, cv2.COLOR_BGR2GRAY).astype(np.float32)


def track(frames, box, search=48):
    """Per-frame (dx, dy) of the mouth area relative to the first frame; None where it is hidden (a hand)."""
    left, top, right, bottom = box
    template = gray(frames[0][top:bottom, left:right])
    out = []
    for frame in frames:
        y0, x0 = max(0, top - search), max(0, left - search)
        window = gray(frame[y0:bottom + search, x0:right + search])
        result = cv2.matchTemplate(window, template, cv2.TM_CCOEFF_NORMED)
        _, score, _, (mx, my) = cv2.minMaxLoc(result)
        out.append([mx + x0 - left, my + y0 - top] if score > 0.6 else None)
    return out


# Mouth area tracked through every clip (video pixels on the hero frame; matches src/lib/mouthWarp.ts LIP).
MOUTH_BOX = (300, 381, 433, 476)


def main():
    clips_dir = Path(sys.argv[1]).expanduser()
    OUT.mkdir(parents=True, exist_ok=True)
    for stale in OUT.glob('mouth-*.webp'):
        stale.unlink()
    for clip in clips_dir.glob('*.mp4'):
        shutil.copy2(clip, OUT / clip.name)
    shutil.copy2(clips_dir / 'poster.jpg', OUT / 'poster.jpg')

    hero = frames_of(clips_dir / 'idle.mp4')[0][0]
    clips = {}
    for clip in sorted(clips_dir.glob('*.mp4')):
        frames, fps = frames_of(clip)
        offsets = track(frames, MOUTH_BOX)
        clips[clip.stem] = {'fps': fps, 'frames': len(frames), 'offsets': offsets}
        moved = max((abs(o[0]) + abs(o[1]) for o in offsets if o), default=0)
        print(f'{clip.stem:10} {len(frames):3} frames, mouth moves up to {moved}px, hidden in {sum(o is None for o in offsets)} frames')

    data = {'width': hero.shape[1], 'height': hero.shape[0], 'clips': clips}
    (OUT / 'track.ts').write_text('// Generated by scripts/build_professor_video.py; do not edit.\n'
                                  f'export default {json.dumps(data, separators=(",", ":"))} as const;\n')


if __name__ == '__main__':
    main()
